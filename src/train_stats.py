"""Per-ID timing stats from leak-free Normal traffic -> artifacts/train_stats.json.

Source: splits.json "stats_source" (Pre_train_*_0, Normal-only). Those files are in training for
every CV fold, so the stats cannot leak any validation fold and features are computed once.
dt is taken within each file per ID (never across files), then S and D are pooled: EDA showed
S ~ D and one shared model is planned.

The artifact holds only facts from stats_source. The coverage check against the other train
files (which needs their labels) goes to reports/train_stats_check.md, never into the artifact.
Usage: python -m src.train_stats
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

from src.load import ROOT, SUBCLASS_CATS, load_processed
from src.splits import SPLITS_PATH

STATS_PATH = ROOT / "artifacts" / "train_stats.json"
CHECK_REPORT_PATH = ROOT / "reports" / "train_stats_check.md"

PERCENTILES = {"p5": 5, "p25": 25, "p75": 75, "p95": 95}
MIN_FRAMES_PER_ID = 30  # below this a per-ID median period is too noisy to trust


def fmt_id(arb_id: int) -> str:
    return f"0x{int(arb_id):03X}"


def load_splits(path: Path = SPLITS_PATH) -> dict:
    return json.loads(Path(path).read_text(encoding="utf-8"))


def per_id_dt(df: pd.DataFrame) -> pd.DataFrame:
    """dt to the previous frame of the same ID within the same file; first frames are dropped."""
    df = df.sort_values(["source_file", "timestamp", "row_idx"], kind="stable")
    dt = df.groupby(["source_file", "arb_id"], observed=True)["timestamp"].diff()
    out = pd.DataFrame({"arb_id": df["arb_id"].to_numpy(), "dt": dt.to_numpy()})
    return out.dropna(subset=["dt"])


def compute_train_stats(files: list[str]) -> dict:
    df = load_processed(names=files, columns=["source_file", "row_idx", "timestamp", "arb_id", "class"])
    missing = set(files) - set(df["source_file"].astype(str).unique())
    if missing:
        raise FileNotFoundError(f"stats_source files not found in data/processed: {sorted(missing)}")
    if (df["class"] != "Normal").any():
        raise ValueError("stats_source must be Normal-only")

    n_frames = df.groupby("arb_id").size()
    too_few = n_frames[n_frames < MIN_FRAMES_PER_ID]
    if len(too_few):
        raise ValueError(f"IDs with < {MIN_FRAMES_PER_ID} frames: {[fmt_id(i) for i in too_few.index]}")

    d = per_id_dt(df)
    per_id = {}
    for arb_id, s in d.groupby("arb_id")["dt"]:
        v = s.to_numpy()
        med = float(np.median(v))
        per_id[fmt_id(arb_id)] = {
            "n": int(n_frames[arb_id]),
            "median_period_s": med,
            **{k: float(np.percentile(v, q)) for k, q in PERCENTILES.items()},
            "mad": float(np.median(np.abs(v - med))),
        }
    known_ids = sorted(n_frames.index)
    if [fmt_id(i) for i in known_ids] != sorted(per_id):
        raise ValueError("every known ID must have dt stats")

    return {
        "created_by": "python -m src.train_stats",
        "source_files": sorted(files),
        "source_rows": {str(k): int(v) for k, v in df.groupby("source_file", observed=True).size().items()},
        "definitions": {
            "dt": "timestamp minus previous frame of the same ID in the same file (seconds)",
            "n": "frames of this ID across source_files",
            "mad": "median(|dt - median_period_s|), unscaled",
            "global_ref_period_s": "median of all pooled per-ID dt values (frame-weighted); "
                                   "ref period for IDs not in per_id",
        },
        "known_ids": [fmt_id(i) for i in known_ids],
        "global_ref_period_s": float(np.median(d["dt"].to_numpy())),
        "per_id": {k: per_id[k] for k in sorted(per_id)},
    }


def load_train_stats(path: Path = STATS_PATH) -> dict:
    """Artifact with IDs as ints: known_ids -> frozenset[int], per_id -> {int: stats}."""
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    return {**raw,
            "known_ids": frozenset(int(i, 16) for i in raw["known_ids"]),
            "per_id": {int(k, 16): v for k, v in raw["per_id"].items()}}


def coverage_report(train_files: list[str], stats: dict) -> str:
    """Train-file IDs vs known_ids. Uses attack-file labels, so it is a report, not an artifact."""
    df = load_processed(names=train_files, columns=["source_file", "arb_id", "class", "subclass"])
    known = set(stats["known_ids"])
    df["id_hex"] = df["arb_id"].map(fmt_id)
    unknown = ~df["id_hex"].isin(known)

    lines = ["# Train stats coverage check", "",
             "Generated by `python -m src.train_stats`. Compares IDs in all train files "
             f"({', '.join(train_files)}) with `known_ids` from {', '.join(stats['source_files'])}. "
             "**Report only: nothing here feeds artifacts/train_stats.json.**", "",
             f"- known_ids: {len(known)}",
             f"- global_ref_period_s: {stats['global_ref_period_s']:.6f}", ""]

    normal_unknown = df[unknown & (df["class"] == "Normal")]
    n_normal = int((df["class"] == "Normal").sum())
    lines += ["## Normal-labelled IDs missing from known_ids", "",
              f"{len(normal_unknown):,} of {n_normal:,} Normal frames "
              f"({len(normal_unknown) / n_normal:.3%}).", ""]
    if len(normal_unknown):
        tab = pd.crosstab(normal_unknown["id_hex"], normal_unknown["source_file"].astype(str))
        tab["total"] = tab.sum(axis=1)
        lines += ["| arb_id | " + " | ".join(tab.columns) + " |", "|" + "---|" * (len(tab.columns) + 1)]
        lines += [f"| {i} | " + " | ".join(f"{v:,}" for v in row) + " |" for i, row in tab.iterrows()]
        lines.append("")

    lines += ["## Frames on IDs not in known_ids, by SubClass", "",
              "Share of each SubClass that `id_seen_in_training = 0` would flag.", "",
              "| subclass | frames | on unknown IDs | share |", "|---|---|---|---|"]
    for sub in SUBCLASS_CATS:
        m = df["subclass"] == sub
        n, u = int(m.sum()), int((m & unknown).sum())
        lines.append(f"| {sub} | {n:,} | {u:,} | {u / n:.2%} |" if n else f"| {sub} | 0 | 0 | - |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    splits = load_splits()
    stats = compute_train_stats(splits["stats_source"])
    STATS_PATH.parent.mkdir(parents=True, exist_ok=True)
    STATS_PATH.write_text(json.dumps(stats, indent=2) + "\n", encoding="utf-8")
    CHECK_REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    CHECK_REPORT_PATH.write_text(coverage_report(splits["train"], stats), encoding="utf-8")

    n = [s["n"] for s in stats["per_id"].values()]
    print(f"source      : {stats['source_files']}  rows={stats['source_rows']}")
    print(f"known_ids   : {len(stats['known_ids'])}  (min frames/ID = {min(n)})")
    print(f"global_ref  : {stats['global_ref_period_s'] * 1e3:.3f} ms")
    print(f"-> {STATS_PATH}\n-> {CHECK_REPORT_PATH}")
